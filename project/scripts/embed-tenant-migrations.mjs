import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsPath = resolve(projectRoot, 'supabase/migrations');
const outputPath = resolve(projectRoot, 'supabase-owner/supabase/functions/owner-provisioning/tenantMigrations.ts');
const filenames = (await readdir(migrationsPath)).filter(name => /^\d+_[a-z0-9_]+\.sql$/i.test(name)).sort();

if (filenames.length === 0) throw new Error(`No tenant migrations found in ${migrationsPath}`);

const migrations = await Promise.all(filenames.map(async filename => {
  const content = await readFile(resolve(migrationsPath, filename), 'utf8');
  const match = filename.match(/^(\d+)_(.+)\.sql$/i);
  if (!match) throw new Error(`Invalid migration filename: ${filename}`);
  return { version: match[1], name: match[2], sql: content };
}));

await writeFile(outputPath,
  `// Generated by scripts/embed-tenant-migrations.mjs. Do not edit by hand.\n` +
  `export const tenantMigrations = ${JSON.stringify(migrations)} as const;\n`,
  'utf8',
);
console.log(`Embedded ${migrations.length} tenant migrations (${migrations.reduce((size, item) => size + item.sql.length, 0)} SQL characters).`);
